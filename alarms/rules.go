package alarms

import (
	"bytes"
	"errors"
	"fmt"
	"sort"
	"strconv"
	"strings"
	"time"
)

// RulesConfig configures Rules.
type RulesConfig struct {
	// Service names the rule group and is a label on every alert, so
	// Alertmanager can route by it. Required.
	Service string
	// Definitions to render. Alarms.Rules fills it from the declared set.
	Definitions []Definition
	// Group is the rule group name; default "<service>-alarms".
	Group string
	// Window is the default increase() lookback for Event alarms; default 5m.
	Window time.Duration
	// Labels are added to every alert (team, runbook). Keys must be valid
	// Prometheus label names and must not collide with the generated ones.
	Labels map[string]string
	// Selector is an extra PromQL label matcher added to every expression,
	// such as `job="customers-api"`, when several services share a
	// Prometheus and the alert must not match the others' series.
	Selector string
}

var generated = map[string]struct{}{"severity": {}, "alarm_type": {}, "alarm_name": {}, "service": {}}

// Rules renders a Prometheus alerting rule file for the definitions:
//
//	groups:
//	  - name: customers-alarms
//	    rules:
//	      - alert: BillingQuotaExceeded
//	        expr: increase(alarms_total{alarm_type="billing",alarm_name="quota_exceeded"}[5m]) > 0
//	        for: 0s
//	        labels: {severity: critical, alarm_type: billing, alarm_name: quota_exceeded, service: customers}
//	        annotations: {summary: ..., description: ...}
//
// Event alarms fire on increase() over Window; State alarms fire when
// alarms_active has been 1 for For. Write the output to the rules
// directory Prometheus loads (a ConfigMap, a file in the chart) and let
// Alertmanager route on severity and service.
func Rules(cfg RulesConfig) ([]byte, error) {
	if cfg.Service == "" {
		return nil, errors.New("alarms: rules: Service is required")
	}
	if cfg.Group == "" {
		cfg.Group = cfg.Service + "-alarms"
	}
	if cfg.Window <= 0 {
		cfg.Window = 5 * time.Minute
	}
	if len(cfg.Definitions) == 0 {
		return nil, errors.New("alarms: rules: no definitions")
	}
	extra := make([]string, 0, len(cfg.Labels))
	for k := range cfg.Labels {
		if !labelNameRe.MatchString(k) {
			return nil, fmt.Errorf("alarms: rules: label %q is not a valid Prometheus label name", k)
		}
		if _, taken := generated[k]; taken {
			return nil, fmt.Errorf("alarms: rules: label %q is generated", k)
		}
		extra = append(extra, k)
	}
	sort.Strings(extra)

	defs := make([]Definition, 0, len(cfg.Definitions))
	seen := map[string]struct{}{}
	for _, d := range cfg.Definitions {
		d = d.withDefaults()
		if err := d.validate(); err != nil {
			return nil, err
		}
		if _, dup := seen[d.key()]; dup {
			return nil, fmt.Errorf("alarms: rules: %s defined twice", d.key())
		}
		seen[d.key()] = struct{}{}
		defs = append(defs, d)
	}
	sort.Slice(defs, func(i, j int) bool { return defs[i].key() < defs[j].key() })

	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by %s for %s. Edit the definitions, not this file.\n", InstrumentationName, cfg.Service)
	b.WriteString("groups:\n")
	fmt.Fprintf(&b, "  - name: %s\n", yamlString(cfg.Group))
	b.WriteString("    rules:\n")
	for _, d := range defs {
		fmt.Fprintf(&b, "      - alert: %s\n", AlertName(d))
		fmt.Fprintf(&b, "        expr: %s\n", expr(d, cfg))
		fmt.Fprintf(&b, "        for: %s\n", promDuration(forOf(d)))
		b.WriteString("        labels:\n")
		fmt.Fprintf(&b, "          severity: %s\n", d.Severity)
		fmt.Fprintf(&b, "          alarm_type: %s\n", d.Type)
		fmt.Fprintf(&b, "          alarm_name: %s\n", d.Name)
		fmt.Fprintf(&b, "          service: %s\n", yamlString(cfg.Service))
		for _, k := range extra {
			fmt.Fprintf(&b, "          %s: %s\n", k, yamlString(cfg.Labels[k]))
		}
		b.WriteString("        annotations:\n")
		fmt.Fprintf(&b, "          summary: %s\n", yamlString(d.Summary))
		fmt.Fprintf(&b, "          description: %s\n", yamlString(description(d, cfg)))
	}
	return b.Bytes(), nil
}

// AlertName is the alert name Rules gives a definition: the type and name
// in PascalCase, "billing/quota_exceeded" → "BillingQuotaExceeded".
func AlertName(d Definition) string {
	var b strings.Builder
	for _, part := range strings.Split(d.Type+"_"+d.Name, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

func expr(d Definition, cfg RulesConfig) string {
	matchers := fmt.Sprintf(`alarm_type=%s,alarm_name=%s`, strconv.Quote(d.Type), strconv.Quote(d.Name))
	if cfg.Selector != "" {
		matchers += "," + cfg.Selector
	}
	if d.Kind == State {
		return fmt.Sprintf("alarms_active{%s} == 1", matchers)
	}
	window := d.Window
	if window <= 0 {
		window = cfg.Window
	}
	return fmt.Sprintf("increase(alarms_total{%s}[%s]) > 0", matchers, promDuration(window))
}

func forOf(d Definition) time.Duration {
	if d.Kind == State {
		return d.For
	}
	return 0
}

func description(d Definition, cfg RulesConfig) string {
	if d.Kind == State {
		return fmt.Sprintf("%s: %s on {{ $labels.instance }} for %s", cfg.Service, d.Summary, promDuration(d.For))
	}
	return fmt.Sprintf("%s: %s ({{ $value | printf \"%%.0f\" }} in the last %s on {{ $labels.instance }})", cfg.Service, d.Summary, promDuration(windowOf(d, cfg)))
}

func windowOf(d Definition, cfg RulesConfig) time.Duration {
	if d.Window > 0 {
		return d.Window
	}
	return cfg.Window
}

// promDuration renders d the way Prometheus parses durations: whole
// units, largest first, zero components omitted ("2m", "1h30m", "0s").
func promDuration(d time.Duration) string {
	if d <= 0 {
		return "0s"
	}
	d = d.Round(time.Millisecond)
	var b strings.Builder
	for _, u := range []struct {
		n time.Duration
		s string
	}{{24 * time.Hour, "d"}, {time.Hour, "h"}, {time.Minute, "m"}, {time.Second, "s"}, {time.Millisecond, "ms"}} {
		if d >= u.n {
			fmt.Fprintf(&b, "%d%s", d/u.n, u.s)
			d %= u.n
		}
	}
	return b.String()
}

// yamlString double-quotes with the escapes YAML shares with Go.
func yamlString(s string) string { return strconv.Quote(s) }
